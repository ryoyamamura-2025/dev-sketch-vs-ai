function katakanaToHiragana(value: string): string {
  return Array.from(value, (character) => {
    const code = character.charCodeAt(0)
    return code >= 0x30a1 && code <= 0x30f6
      ? String.fromCharCode(code - 0x60)
      : character
  }).join('')
}

export function toHiraganaCategoryLabel(value: string): string {
  return EXPLICIT_READINGS[value] ?? katakanaToHiragana(value)
}

export function normalizeCategoryLabelsToHiragana(): void {
  for (const category of QUICK_DRAW_CATEGORIES) {
    category.ja = toHiraganaCategoryLabel(category.ja)
  }
}
